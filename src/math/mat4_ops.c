#include "fdf.h"

void	translate_mat4(t_mat4 *m, t_vec3 v)
{
	m->m[0][3] += v.x;
	m->m[1][3] += v.y;
	m->m[2][3] += v.z;
}

t_mat4	mat4_mul(t_mat4 a, t_mat4 b)
{
	t_mat4	res;
	int		i;
	int		j;
	int		k;

	i = 0;
	while (i < 4)
	{
		j = 0;
		while (j < 4)
		{
			res.m[i][j] = 0.0;
			k = 0;
			while (k < 4)
			{
				res.m[i][j] += a.m[i][k] * b.m[k][j];
				k++;
			}
			j++;
		}
		i++;
	}
	return (res);
}

t_vec4	mat4_apply(t_mat4 m, t_vec4 v)
{
	t_vec4	r;

	r.x = m.m[0][0] * v.x + m.m[0][1] * v.y + m.m[0][2] * v.z + m.m[0][3] * v.w;
	r.y = m.m[1][0] * v.x + m.m[1][1] * v.y + m.m[1][2] * v.z + m.m[1][3] * v.w;
	r.z = m.m[2][0] * v.x + m.m[2][1] * v.y + m.m[2][2] * v.z + m.m[2][3] * v.w;
	r.w = m.m[3][0] * v.x + m.m[3][1] * v.y + m.m[3][2] * v.z + m.m[3][3] * v.w;
	return (r);
}

void	scale_mat4_by(t_mat4 *m, double s)
{
	m->m[0][0] = m->m[0][0] * s;
	m->m[0][1] = m->m[0][1] * s;
	m->m[0][2] = m->m[0][2] * s;
	m->m[0][3] = m->m[0][3] * s;
	m->m[1][0] = m->m[1][0] * s;
	m->m[1][1] = m->m[1][1] * s;
	m->m[1][2] = m->m[1][2] * s;
	m->m[1][3] = m->m[1][3] * s;
	m->m[2][0] = m->m[2][0] * s;
	m->m[2][1] = m->m[2][1] * s;
	m->m[2][2] = m->m[2][2] * s;
	m->m[2][3] = m->m[2][3] * s;
	m->m[3][0] = m->m[3][0] * s;
	m->m[3][1] = m->m[3][1] * s;
	m->m[3][2] = m->m[3][2] * s;
	m->m[3][3] = m->m[3][3] * s;
}

t_mat4	transpose_mat4(t_mat4 m)
{
	t_mat4	t;

	t.m[0][0] = m.m[0][0];
	t.m[0][1] = m.m[1][0];
	t.m[0][2] = m.m[2][0];
	t.m[0][3] = m.m[3][0];
	t.m[1][0] = m.m[0][1];
	t.m[1][1] = m.m[1][1];
	t.m[1][2] = m.m[2][1];
	t.m[1][3] = m.m[3][1];
	t.m[2][0] = m.m[0][2];
	t.m[2][1] = m.m[1][2];
	t.m[2][2] = m.m[2][2];
	t.m[2][3] = m.m[3][2];
	t.m[3][0] = m.m[0][3];
	t.m[3][1] = m.m[1][3];
	t.m[3][2] = m.m[2][3];
	t.m[3][3] = m.m[3][3];
	return (t);
}
