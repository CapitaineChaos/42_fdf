#include "fdf.h"

t_vec3	trans_mat4_to_vec3(t_mat4 m)
{
	t_vec3	v;

	v.x = m.m[0][3];
	v.y = m.m[1][3];
	v.z = m.m[2][3];
	return (v);
}
